import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CRON_JOB_DEFINITIONS } from "@shared/lib/cron-jobs";
import { parseStrictCliArgs, runDirectCli, writeCliHelpIfRequested } from "../lib/cli-args.mjs";
import { LANE_FRESHNESS_REVIEW_NOTES } from "../lib/lane-freshness-review";
import { renderMarkdownRows } from "../lib/markdown-report";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const DOC_PATH = "docs/process/lane-freshness-matrix.md";
export const START_MARKER = "<!-- GENERATED-START: lane-freshness-matrix -->";
export const END_MARKER = "<!-- GENERATED-END: lane-freshness-matrix -->";
const USAGE = `Usage: node --import tsx scripts/maintenance/generate-lane-freshness-matrix.ts [options]

Options:
  --check       Check freshness without writing
  -h, --help    Show this help`;

const formatDuration = (sec: number) =>
  sec % 86_400 === 0 ? `${sec / 86_400}d` : sec % 3_600 === 0 ? `${sec / 3_600}h` : `${sec / 60}m`;

export function renderLaneFreshnessMatrix(notes = LANE_FRESHNESS_REVIEW_NOTES): string {
  const jobs = new Set(CRON_JOB_DEFINITIONS.map(({ job }) => job));
  if (jobs.size !== CRON_JOB_DEFINITIONS.length) throw new Error("Duplicate job id in CRON_JOB_DEFINITIONS");
  for (const job of Object.keys(notes)) {
    if (!jobs.has(job)) throw new Error(`Unknown lane freshness review note: ${job}`);
  }
  for (const { job } of CRON_JOB_DEFINITIONS) {
    if (!notes[job]?.trim()) throw new Error(`Missing lane freshness review note: ${job}`);
  }
  return [
    START_MARKER,
    "<!-- Generated by scripts/maintenance/generate-lane-freshness-matrix.ts. Do not edit by hand. -->",
    "",
    `The registry supplies all ${CRON_JOB_DEFINITIONS.length} logical jobs; owner-review prose lives in \`scripts/lib/lane-freshness-review.ts\`.`,
    "",
    ...renderMarkdownRows({
      headings: ["Logical job", "Effective interval", "Current freshness budget / evidence", "Current status impact", "Proposed tolerated incompleteness (owner review)"],
      rows: CRON_JOB_DEFINITIONS,
      pipeStyle: "wrapped",
      cells: ({ job, intervalSec, scheduleKey, freshnessSurface, statusImpact }) => [
        `\`${job}\``,
        `${formatDuration(intervalSec)}${scheduleKey === "monthlyYieldAudit" ? " nominal" : ""}`,
        `${formatDuration(2 * intervalSec)} ${freshnessSurface === "consumer" ? "C" : "O"}`,
        statusImpact,
        notes[job],
      ],
    }),
    "",
    END_MARKER,
  ].join("\n");
}

export function replaceLaneFreshnessMatrix(doc: string, block: string): string {
  const start = doc.indexOf(START_MARKER);
  const end = doc.indexOf(END_MARKER);
  if (start === -1 || end < start
      || doc.indexOf(START_MARKER, start + START_MARKER.length) !== -1
      || doc.indexOf(END_MARKER, end + END_MARKER.length) !== -1) {
    throw new Error("Expected exactly one complete lane-freshness-matrix generated block");
  }
  return `${doc.slice(0, start)}${block}${doc.slice(end + END_MARKER.length)}`;
}

export function runLaneFreshnessMatrixCli(argv: readonly string[], repoRoot = ROOT): void {
  const { values } = parseStrictCliArgs(argv, { options: { check: { type: "boolean" } } });
  if (writeCliHelpIfRequested(values, USAGE)) return;
  const path = resolve(repoRoot, DOC_PATH);
  const existing = readFileSync(path, "utf8");
  const next = replaceLaneFreshnessMatrix(existing, renderLaneFreshnessMatrix());
  if (values.check === true) {
    if (next !== existing) {
      throw new Error(`${DOC_PATH} is out of date. Run node --import tsx scripts/maintenance/generate-lane-freshness-matrix.ts`);
    }
    console.log("Lane freshness matrix is current");
    return;
  }
  if (next === existing) {
    console.log("Lane freshness matrix unchanged");
    return;
  }
  writeFileSync(path, next, "utf8");
  console.log("Lane freshness matrix regenerated");
}

runDirectCli(import.meta.url, () => runLaneFreshnessMatrixCli(process.argv.slice(2)), {
  label: "lane-freshness-matrix",
  usage: USAGE,
});
