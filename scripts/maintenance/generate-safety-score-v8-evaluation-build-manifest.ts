export interface V8EvaluationBuildManifestFile {
  path: string;
  sha256: string;
}

export interface V8EvaluationBuildManifest {
  schemaVersion: 1;
  domain: typeof V8_EVALUATION_BUILD_DIGEST_DOMAIN;
  files: V8EvaluationBuildManifestFile[];
  digest: string;
}

function sha256(value: string | Buffer): string {
  return createHash("sha256").update(value).digest("hex");
}

export function collectV8EvaluationBuildSourcePaths(root = REPO_ROOT): string[] {
  const paths = [...V8_EVALUATION_BUILD_SOURCE_PATHS].sort();
  const missing = paths.filter((path) => !existsSync(resolve(root, path)));
  if (missing.length > 0) {
    throw new Error(`Missing Safety Score v8 evaluation-build sources: ${missing.join(", ")}`);
  }
  return paths;
}

export function buildV8EvaluationBuildManifest(root = REPO_ROOT): V8EvaluationBuildManifest {
  const files = collectV8EvaluationBuildSourcePaths(root).map((path) => ({
    path,
    sha256: sha256(readFileSync(resolve(root, path))),
  }));
  const payload: Omit<V8EvaluationBuildManifest, "digest"> = {
    schemaVersion: 1,
    domain: V8_EVALUATION_BUILD_DIGEST_DOMAIN,
    files,
  };
  return { ...payload, digest: sha256(JSON.stringify(payload)) };
}

export function renderV8EvaluationBuildManifest(manifest: V8EvaluationBuildManifest): string {
  return [
    "// Generated by scripts/maintenance/generate-safety-score-v8-evaluation-build-manifest.ts.",
    "// Do not edit manually.",
    `export const SAFETY_SCORE_V8_EVALUATION_BUILD_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;`,
    "",
    "export const SAFETY_SCORE_V8_EVALUATION_BUILD_DIGEST =",
    "  SAFETY_SCORE_V8_EVALUATION_BUILD_MANIFEST.digest;",
    "",
  ].join("\n");
}

export function runV8EvaluationBuildManifestGenerator(args = process.argv.slice(2), root = REPO_ROOT): void {
  const unknown = args.filter((arg) => arg !== "--check");
  if (unknown.length > 0) throw new Error(`Unknown arguments: ${unknown.join(", ")}`);
  const check = args.includes("--check");
  const manifest = buildV8EvaluationBuildManifest(root);
  syncGeneratedArtifacts({
    artifacts: [{ path: resolve(root, OUTPUT_PATH), contents: renderV8EvaluationBuildManifest(manifest) }],
    check,
    staleMessage:
      "Safety Score v8 evaluation-build manifest is stale. Run npm run generate:safety-score-v8-evaluation-build.",
    currentMessage: `Safety Score v8 evaluation-build manifest is current (${manifest.digest}).`,
    writtenMessage: `Generated Safety Score v8 evaluation-build manifest (${manifest.digest}).`,
  });
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  runV8EvaluationBuildManifestGenerator();
}
