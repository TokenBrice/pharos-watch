import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CRON_SCHEDULE_CADENCES } from "@shared/lib/cron-cadences";
import { CRON_SCHEDULES, CRON_TRIGGER_SCHEDULES, type CronScheduleKey } from "@shared/lib/cron-jobs";
import {
  DEFAULT_CRON_TIMEOUT_MS,
  SCHEDULED_SLOT_PLANS,
  SCHEDULED_TASK_DESCRIPTORS,
  type ScheduledTaskDuePolicy,
  type ScheduledWorkerRole,
} from "@shared/lib/scheduled-runner-registry";
import { evaluateCronScheduleSync, parseWranglerCronTriggers } from "../ci/check-cron-schedule-sync";
import { parseStrictCliArgs, runDirectCli, writeCliHelpIfRequested } from "../lib/cli-args.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const DOC_PATH = "docs/worker-infrastructure.md";
const HEADING = "## Cron Scheduling\n";
export const START_MARKER = "<!-- GENERATED-START: cron-doc-view -->";
export const END_MARKER = "<!-- GENERATED-END: cron-doc-view -->";
export const TASK_START_MARKER = "<!-- GENERATED-START: scheduled-task-topology -->";
export const TASK_END_MARKER = "<!-- GENERATED-END: scheduled-task-topology -->";
const USAGE = `Usage: node --import tsx scripts/maintenance/generate-cron-doc-view.ts [options]

Options:
  --check       Check freshness without writing
  -h, --help    Show this help`;

type WorkerTriggers = Record<ScheduledWorkerRole, readonly string[]>;

export function loadCronDocTriggers(repoRoot: string): WorkerTriggers {
  return {
    public: parseWranglerCronTriggers(readFileSync(resolve(repoRoot, "worker/wrangler.toml"), "utf8")),
    heavy: parseWranglerCronTriggers(readFileSync(resolve(repoRoot, "worker/wrangler.heavy.toml"), "utf8")),
  };
}

export function renderCronDocView(triggers: WorkerTriggers): string {
  const report = evaluateCronScheduleSync({ wranglerCronTriggers: triggers });
  if (report.failed) {
    throw new Error("Cron sources disagree; resolve check:cron-sync findings before generating the cadence table");
  }
  const rows = (Object.keys(CRON_SCHEDULES) as CronScheduleKey[]).map((key) => {
    const plan = SCHEDULED_SLOT_PLANS[key];
    if (plan.scheduleKey !== key || plan.schedule !== CRON_SCHEDULES[key]) {
      throw new Error(`Cron slot identity disagrees for ${key}`);
    }
    const cadence = CRON_SCHEDULE_CADENCES[key];
    const physical = CRON_TRIGGER_SCHEDULES[key].map((expression) => `\`${expression}\``).join("<br>");
    return `| \`${key}\` | \`${CRON_SCHEDULES[key]}\` | ${cadence.intervalSec} / ${cadence.offsetSec} | ${physical} | ${plan.worker} |`;
  });
  return [
    START_MARKER,
    "<!-- Generated by scripts/maintenance/generate-cron-doc-view.ts. Do not edit by hand. -->",
    "",
    "UTC inventory from `shared/lib/cron-jobs.ts`, `shared/lib/cron-cadences.ts`, `shared/lib/scheduled-runner-registry.ts`, `worker/wrangler.toml` and `worker/wrangler.heavy.toml`. Public = `stablecoin-api`; heavy = private `stablecoin-heavy` (scheduled plans plus the project-tape fetch executor).",
    "",
    "Interval / offset are logical-slot seconds, not job freshness or delivery evidence. Aliases can move without changing logical slot identity. The monthly cron owns calendar firing dates.",
    "",
    "| Logical slot key | Logical cron | Interval / offset (s) | Physical trigger expression(s) | Worker role |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
    END_MARKER,
  ].join("\n");
}

export function renderScheduledTaskTopology(): string {
  const dueLabels: Record<ScheduledTaskDuePolicy, string> = {
    always: "every occurrence",
    "conditional-admission": "admission evidence required",
    "dex-publication": "DEX publication slot",
    monday: "Monday UTC",
  };
  const rows = SCHEDULED_TASK_DESCRIPTORS.map((descriptor) => {
    const position = descriptor.chainIndex == null
      ? `side stage, task ${descriptor.taskIndex + 1}`
      : `chain ${descriptor.chainIndex + 1}, task ${descriptor.taskIndex + 1}`;
    const { heartbeatSec, maxRenewFailures } = descriptor.leaseOptions;
    const lease = descriptor.statusTracked
      ? heartbeatSec == null && maxRenewFailures == null
        ? "TTL-derived defaults"
        : `${heartbeatSec ?? "TTL-derived"} / ${maxRenewFailures ?? "default"}`
      : "not leased by the scheduled wrapper";
    return `| \`${descriptor.scheduleKey}\` | \`${descriptor.job}\` | ${position} | ${descriptor.producerKind} | ${descriptor.maxConnections} | ${descriptor.timeoutMs / 1_000} | ${lease} | ${dueLabels[descriptor.due]} |`;
  });
  return [
    TASK_START_MARKER,
    "<!-- Generated by scripts/maintenance/generate-cron-doc-view.ts. Do not edit by hand. -->",
    "",
    "## Scheduled Task Topology",
    "",
    "For a simple job joining an existing lane, there are at most four authoritative production edits:",
    "",
    "1. Implement the job under `worker/src/cron/` using the existing domain family.",
    "2. Bind it in the existing lane handler under `worker/src/handlers/scheduled/`; keep lazy runner imports lazy.",
    "3. Add its status/connection metadata in `shared/lib/cron-jobs.ts` (budget-only work uses that same authority).",
    "4. Add it to the existing slot chain or side stage in `shared/lib/scheduled-runner-registry.ts`; declare exceptional timeout, lease or due metadata in that slot's `taskPolicies`.",
    "",
    `Descriptors supply the default ${DEFAULT_CRON_TIMEOUT_MS / 1_000}-second timeout, TTL-derived lease behavior and every-occurrence due policy. Timeout clipping and lease TTL calculation remain runtime concerns; the timeout column is the configured cap, not extra slot time. Side stages retain their own execution/admission policy and are not automatically leased or timed by the scheduled wrapper.`,
    "",
    "Add focused tests and owning domain documentation, then regenerate this view with `node --import tsx scripts/maintenance/generate-cron-doc-view.ts`. These evidence/generated edits are not additional production authorities. New lanes, expressions or shared identities require their existing cadence, deployment and capacity review; they are not the simple-job path.",
    "",
    "The registry-iterating scheduled-runner contract tests check descriptor coverage, timeout/lease metadata and due policies; `check:cron-sync`, `check:cron-connections` and the `cron-doc-view` generated-artifact check enforce deployment, capacity and documentation parity.",
    "",
    "Chain/task positions below are one-based. Separate chains run independently; tasks within each chain are ordered. Lease overrides show heartbeat seconds / consecutive renewal failures; defaults remain in `worker/src/lib/cron-lease-primitives.ts`.",
    "",
    "| Logical slot key | Job | Execution position | Producer kind | Connections | Timeout (s) | Lease overrides (s / failures) | Due policy |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    TASK_END_MARKER,
  ].join("\n");
}

export function replaceCronDocView(doc: string, block: string, section: "cadence" | "tasks" = "cadence"): string {
  const startMarker = section === "cadence" ? START_MARKER : TASK_START_MARKER;
  const endMarker = section === "cadence" ? END_MARKER : TASK_END_MARKER;
  const start = doc.indexOf(startMarker);
  const end = doc.indexOf(endMarker);
  if (start === -1 && end === -1) {
    const anchor = section === "cadence" ? HEADING : "## Shared Database Helpers\n";
    const heading = doc.indexOf(anchor);
    if (heading === -1 || doc.indexOf(anchor, heading + anchor.length) !== -1) {
      throw new Error(`Expected exactly one ${section === "cadence" ? "Cron Scheduling" : "Shared Database Helpers"} heading`);
    }
    const insertion = section === "cadence" ? heading + anchor.length : heading;
    return `${doc.slice(0, insertion)}\n${block}\n\n${doc.slice(insertion)}`;
  }
  if (start === -1 || end < start
      || doc.indexOf(startMarker, start + startMarker.length) !== -1
      || doc.indexOf(endMarker, end + endMarker.length) !== -1) {
    throw new Error(`Expected exactly one complete ${section === "cadence" ? "cron-doc-view" : "scheduled-task-topology"} generated block`);
  }
  return `${doc.slice(0, start)}${block}${doc.slice(end + endMarker.length)}`;
}

export function runCronDocViewCli(argv: readonly string[], repoRoot = ROOT): void {
  const { values } = parseStrictCliArgs(argv, { options: { check: { type: "boolean" } } });
  if (writeCliHelpIfRequested(values, USAGE)) return;
  const path = resolve(repoRoot, DOC_PATH);
  const existing = readFileSync(path, "utf8");
  const cadenceDoc = replaceCronDocView(existing, renderCronDocView(loadCronDocTriggers(repoRoot)));
  const next = replaceCronDocView(cadenceDoc, renderScheduledTaskTopology(), "tasks");
  if (values.check === true) {
    if (next !== existing) {
      throw new Error(`${DOC_PATH} cron view is out of date. Run node --import tsx scripts/maintenance/generate-cron-doc-view.ts`);
    }
    console.log(`${DOC_PATH} cron view is current`);
    return;
  }
  if (next === existing) {
    console.log(`${DOC_PATH} cron view unchanged`);
    return;
  }
  writeFileSync(path, next, "utf8");
  console.log(`${DOC_PATH} cron view regenerated`);
}

runDirectCli(import.meta.url, () => runCronDocViewCli(process.argv.slice(2)), {
  label: "cron-doc-view",
  usage: USAGE,
});
