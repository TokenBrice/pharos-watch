#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "../..");
const SOURCE_JSON_REL = "shared/data/stablecoins/coins.generated.json";
const OUTPUT_TS_REL = "shared/data/stablecoins/coins.prevalidated.generated.ts";
const REPORT_CARD_FINGERPRINT_TS_REL =
  "shared/data/stablecoins/report-card-registry-fingerprint.generated.ts";
const SOURCE_JSON_ABS = resolve(REPO_ROOT, SOURCE_JSON_REL);
const OUTPUT_TS_ABS = resolve(REPO_ROOT, OUTPUT_TS_REL);
const REPORT_CARD_FINGERPRINT_TS_ABS = resolve(REPO_ROOT, REPORT_CARD_FINGERPRINT_TS_REL);
const CHECK_MODE = process.argv.includes("--check");

/**
 * Synchronous FNV-1a 32-bit hash. Cheap, deterministic, and runs anywhere
 * (Node, Cloudflare Workers, browsers) without crypto APIs. Used purely as
 * a drift fingerprint between the prevalidated TS module and the source JSON;
 * collisions are not a security concern here.
 */
function fnv1a32(input) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = (hash + ((hash << 1) + (hash << 4) + (hash << 7) + (hash << 8) + (hash << 24))) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

function computeFingerprint(parsed) {
  // Stable input: re-stringify the parsed JSON so generator and runtime
  // hash the same canonical form regardless of source-file whitespace.
  return fnv1a32(JSON.stringify(parsed));
}

const rawJson = readFileSync(SOURCE_JSON_ABS, "utf8");
const parsed = JSON.parse(rawJson);

if (!Array.isArray(parsed)) {
  console.error(`[prevalidated-registry] ${SOURCE_JSON_REL} is not a JSON array`);
  process.exit(1);
}

function runAuthoritativeValidation() {
  const result = spawnSync("npm", ["run", "-s", "check:stablecoin-data"], {
    cwd: REPO_ROOT,
    stdio: "inherit",
  });

  if (result.error) {
    console.error(`[prevalidated-registry] Failed to run authoritative validation: ${result.error.message}`);
    process.exit(1);
  }

  if (result.status !== 0) {
    console.error("[prevalidated-registry] Refusing to emit unchecked registry snapshot");
    process.exit(result.status ?? 1);
  }
}

function computeReportCardRegistryFingerprint() {
  const script = `
import { DEAD_STABLECOINS } from "./shared/lib/dead-stablecoins.ts";
import { sha256Hex } from "./shared/lib/sha256.ts";
import { stableJsonStringifyV1 } from "./shared/lib/stable-json.ts";
import { ACTIVE_STABLECOINS, FROZEN_STABLECOINS } from "./shared/lib/stablecoins/registry.ts";

const fingerprint = sha256Hex(
  stableJsonStringifyV1({
    domain: "report-cards.fixed-input.registry.v1",
    activeStablecoins: [...ACTIVE_STABLECOINS].sort((left, right) => left.id.localeCompare(right.id)),
    frozenStablecoins: [...FROZEN_STABLECOINS].sort((left, right) => left.id.localeCompare(right.id)),
    deadStablecoins: [...DEAD_STABLECOINS].sort((left, right) => left.id.localeCompare(right.id)),
  }),
);
console.log(fingerprint);
`;
  const result = spawnSync(process.execPath, ["node_modules/tsx/dist/cli.mjs", "-e", script], {
    cwd: REPO_ROOT,
    encoding: "utf8",
  });

  if (result.error) {
    console.error(`[prevalidated-registry] Failed to compute report-card registry fingerprint: ${result.error.message}`);
    process.exit(1);
  }
  if (result.status !== 0) {
    if (result.stderr) process.stderr.write(result.stderr);
    console.error("[prevalidated-registry] Failed to compute report-card registry fingerprint");
    process.exit(result.status ?? 1);
  }

  const computed = result.stdout.trim();
  if (!/^[a-f0-9]{64}$/.test(computed)) {
    console.error(`[prevalidated-registry] Invalid report-card registry fingerprint output: ${computed}`);
    process.exit(1);
  }
  return computed;
}

runAuthoritativeValidation();

const fingerprint = computeFingerprint(parsed);

const tsContents = `// @generated by scripts/maintenance/generate-stablecoin-prevalidated-registry.mjs
// Do not edit by hand. Run \`node scripts/maintenance/generate-stablecoin-prevalidated-registry.mjs\`
// after modifying any shared/data/stablecoins/coins/*.json file or
// shared/data/stablecoins/coins.generated.json.
//
// This module mirrors coins.generated.json as a typed snapshot so the
// Worker / Next.js runtime can trust the checked artifact without bundling
// the full Zod registry validator into browser-facing chunks. The generator
// runs the authoritative stablecoin-data validation before emitting.

import type { StablecoinMeta } from "../../types";
import coinsGenerated from "./coins.generated.json";

// FNV-1a 32-bit fingerprint of \`coins.generated.json\` at generation time: ${fingerprint}.

/**
 * Pre-validated stablecoin metas, exposed in source order. The snapshot
 * is emitted only after \`npm run check:stablecoin-data\` performs the
 * authoritative Zod + invariant validation.
 */
export const STABLECOIN_META_ASSETS_PREVALIDATED: readonly StablecoinMeta[] =
  coinsGenerated as readonly StablecoinMeta[];
`;

if (CHECK_MODE) {
  const current = existsSync(OUTPUT_TS_ABS) ? readFileSync(OUTPUT_TS_ABS, "utf8") : "";
  if (current !== tsContents) {
    console.error(`${OUTPUT_TS_REL} is stale. Run: node scripts/maintenance/generate-stablecoin-prevalidated-registry.mjs`);
    process.exit(1);
  }
} else {
  mkdirSync(dirname(OUTPUT_TS_ABS), { recursive: true });
  writeFileSync(OUTPUT_TS_ABS, tsContents, "utf8");
  console.log(`${OUTPUT_TS_REL}: wrote prevalidated registry snapshot (fingerprint ${fingerprint}, ${parsed.length} entries)`);
}

const reportCardRegistryFingerprint = computeReportCardRegistryFingerprint();
const reportCardFingerprintContents = `// @generated by scripts/maintenance/generate-stablecoin-prevalidated-registry.mjs
// Do not edit by hand. Run \`node scripts/maintenance/generate-stablecoin-prevalidated-registry.mjs\`
// after modifying the tracked or dead stablecoin registries.

/**
 * SHA-256 of the canonical report-card registry identity projection.
 * The generator computes this from the fully validated registry so Worker
 * requests do not serialize and hash the full catalog at runtime.
 */
export const REPORT_CARDS_REGISTRY_FINGERPRINT =
  "${reportCardRegistryFingerprint}";
`;

if (CHECK_MODE) {
  const current = existsSync(REPORT_CARD_FINGERPRINT_TS_ABS)
    ? readFileSync(REPORT_CARD_FINGERPRINT_TS_ABS, "utf8")
    : "";
  if (current !== reportCardFingerprintContents) {
    console.error(
      `${REPORT_CARD_FINGERPRINT_TS_REL} is stale. Run: node scripts/maintenance/generate-stablecoin-prevalidated-registry.mjs`,
    );
    process.exit(1);
  }
  console.log(
    `${OUTPUT_TS_REL} and ${REPORT_CARD_FINGERPRINT_TS_REL}: generated registries are current ` +
      `(catalog fingerprint ${fingerprint}, report-card fingerprint ${reportCardRegistryFingerprint}, ${parsed.length} entries)`,
  );
} else {
  mkdirSync(dirname(REPORT_CARD_FINGERPRINT_TS_ABS), { recursive: true });
  writeFileSync(REPORT_CARD_FINGERPRINT_TS_ABS, reportCardFingerprintContents, "utf8");
  console.log(
    `${REPORT_CARD_FINGERPRINT_TS_REL}: wrote report-card registry fingerprint (${reportCardRegistryFingerprint})`,
  );
}
