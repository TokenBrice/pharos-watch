import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { parse as parseYaml } from "yaml";
import { z } from "zod";

const stepSchema = z.object({
  id: z.string().optional(), name: z.string().optional(), uses: z.string().optional(), run: z.string().optional(),
  if: z.string().optional(), "continue-on-error": z.boolean().optional(),
  with: z.record(z.string(), z.unknown()).default({}),
  env: z.record(z.string(), z.unknown()).default({}),
});
const readYaml = (path: string): unknown => parseYaml(readFileSync(resolve(process.cwd(), path), "utf8"));
const { runs: { steps } } = z.object({
  inputs: z.record(z.string(), z.object({ default: z.string() })),
  outputs: z.record(z.string(), z.object({ value: z.string() })),
  runs: z.object({ steps: z.array(stepSchema) }),
})
  .parse(readYaml(".github/actions/setup-workspace/action.yml"));

describe("setup-workspace caches", () => {
  it("guards generated bytes before publishing the required workspace", () => {
    const bootstrap = steps.findIndex((step) => step.run === "npm run bootstrap:generated:history");
    const guard = steps.findIndex((step) => step.name === "Verify bootstrap preserved committed artifacts");
    const restore = steps.findIndex((step) => step.run?.startsWith("tar --zstd -xf"));
    const pack = steps.findIndex((step) => step.name === "Package required workspace");
    const upload = steps.findIndex((step) => step.uses?.startsWith("actions/upload-artifact@"));
    expect(bootstrap).toBeGreaterThan(-1);
    expect(guard).toBeGreaterThan(bootstrap);
    expect(restore).toBeGreaterThan(-1);
    expect(guard).toBeGreaterThan(restore);
    expect(pack).toBeGreaterThan(guard);
    expect(upload).toBeGreaterThan(pack);
    expect(steps[guard]["continue-on-error"]).toBeUndefined();
    expect(steps[guard].if).toBe("${{ inputs.workspace-artifact != 'none' || (inputs.install-deps == 'true' && inputs.bootstrap-generated == 'true') }}");
  });


  it("publishes the producer attempt and restores that name unchanged on a partial rerun", () => {
    const resolver = steps.find((step) => step.id === "workspace-artifact-name")!;
    const download = steps.find((step) => step.uses?.startsWith("actions/download-artifact@"))!;
    expect(resolver.env.WORKSPACE_ARTIFACT_NAME).toBe("${{ inputs.workspace-artifact-name }}");
    expect(resolver.run).not.toContain("${{");
    expect(steps.indexOf(resolver)).toBeLessThan(steps.indexOf(download));
    const root = mkdtempSync(join(tmpdir(), "pharos-workspace-name-"));
    try {
      const output = join(root, "output");
      const env = {
        ...process.env, GITHUB_RUN_ID: "123", GITHUB_RUN_ATTEMPT: "2",
        GITHUB_SHA: "a".repeat(40), GITHUB_OUTPUT: output,
      };
      const run = (mode: string, name: string) => spawnSync("bash", ["-e", "-c", resolver.run!], {
        env: { ...env, WORKSPACE_ARTIFACT_MODE: mode, WORKSPACE_ARTIFACT_NAME: name },
        encoding: "utf8",
      });
      expect(run("publish", "").status).toBe(0);
      expect(readFileSync(output, "utf8")).toBe(`name=pr-workspace-123-2-${env.GITHUB_SHA}\n`);
      rmSync(output);
      const producerName = `pr-workspace-123-1-${env.GITHUB_SHA}`;
      expect(run("restore", producerName).status).toBe(0);
      expect(readFileSync(output, "utf8")).toBe(`name=${producerName}\n`);
      rmSync(output);
      for (const name of [
        "", `pr-workspace-456-1-${env.GITHUB_SHA}`, "pr-workspace-123-1-" + "b".repeat(40),
        `pr-workspace-123-0-${env.GITHUB_SHA}`, `${producerName}\ninjected=value`,
        `$(touch ${join(root, "injected")})`,
      ]) {
        expect(run("restore", name).status).toBe(1);
      }
      expect(() => readFileSync(output)).toThrow();
      expect(() => readFileSync(join(root, "injected"))).toThrow();
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("restores an exact-key dependency cache without generated outputs", () => {
    const { inputs } = z.object({
      inputs: z.record(z.string(), z.object({ default: z.string() })),
    }).parse(readYaml(".github/actions/setup-workspace/action.yml"));
    expect(inputs["node-modules-cache"].default).toBe("false");
    const restore = steps.find((step) => step.id === "node-modules-cache")!;
    expect(restore.uses).toMatch(/^actions\/cache\/restore@[0-9a-f]{40}$/);
    expect(restore.if).toBe("${{ inputs.install-deps == 'true' && inputs.node-modules-cache == 'true' }}");
    // Exact key only: no restore-keys may substitute a tree built from another
    // lockfile, Node version, platform or npm configuration.
    expect(restore.with.key).toBe(
      "node-modules-${{ runner.os }}-${{ runner.arch }}-${{ inputs.node-version }}-${{ hashFiles('package-lock.json', 'package.json', 'worker/package.json', 'shared/contracts/package.json', '.npmrc') }}",
    );
    expect(restore.with["restore-keys"]).toBeUndefined();
    // A cache outage falls back to npm ci instead of failing the job.
    expect(restore["continue-on-error"]).toBe(true);
    const paths = String(restore.with.path).trim().split("\n");
    expect(paths).toEqual(["node_modules", "worker/node_modules", "shared/contracts/node_modules"]);
    // Generated outputs are deliberately absent so the bootstrap guard keeps
    // detecting a repaired or stale tracked artifact.
    expect(paths.some((path) => /generated|public|shared\/data/.test(path))).toBe(false);

    const miss = "steps.node-modules-cache.outputs.cache-hit != 'true'";
    const install = steps.findIndex((step) => step.run === "npm ci" && step.if?.includes(miss));
    const save = steps.findIndex((step) => step.name === "Save installed dependencies");
    expect(install).toBeGreaterThan(steps.indexOf(restore));
    expect(save).toBeGreaterThan(install);
    expect(steps[save].uses).toMatch(/^actions\/cache\/save@[0-9a-f]{40}$/);
    expect(steps[save].if).toContain(miss);
    expect(steps[save]["continue-on-error"]).toBe(true);
    expect(steps[save].with.key).toBe("${{ steps.node-modules-cache.outputs.cache-primary-key }}");
    // Selecting the cache off keeps today's plain npm ci.
    expect(steps.some((step) => step.run === "npm ci"
      && step.if === "${{ inputs.install-deps == 'true' && inputs.node-modules-cache != 'true' }}")).toBe(true);
  });

  it("publishes validated lint and compiler state before unrelated nightly guards can fail", () => {
    const workflow = z.object({ jobs: z.record(z.string(), z.object({ steps: z.array(stepSchema) })) })
      .parse(readYaml(".github/workflows/nightly-validation.yml"));
    const nightly = workflow.jobs["full-static"].steps;
    const save = nightly.findIndex((step) => step.uses?.startsWith("actions/cache/save@"));
    expect(save).toBeGreaterThan(-1);
    for (const command of ["lint", "typecheck", "typecheck:worker"]) {
      const index = nightly.findIndex((step) => step.run === `npm run ${command}`);
      expect(index).toBeGreaterThan(-1);
      expect(index).toBeLessThan(save);
      expect(nightly[index]["continue-on-error"]).toBeUndefined();
      // Still executes independently of earlier mandatory failures.
      expect(nightly[index].if).toContain("!cancelled()");
      expect(nightly[index].if).toContain("steps.workspace.outcome == 'success'");
      // The cache publishes only once this command's state is validated.
      expect(nightly[save].if).toContain(`steps.${nightly[index].id}.outcome == 'success'`);
    }
    expect(nightly[save - 1].run).toBe("npm run typecheck:worker");
    expect(nightly[save + 1].run).toBe("npm run lint:typed");
    expect(nightly[save].if).toContain("!cancelled()");
    expect(nightly[save]["continue-on-error"]).toBeUndefined();
    expect(nightly[save].with.key).toBe("${{ steps.workspace.outputs.static-cache-key }}");
    expect(steps.filter((step) => step.uses?.startsWith("actions/cache/save@")).map((step) => step.name))
      .toEqual(["Save installed dependencies"]);
  });

});
