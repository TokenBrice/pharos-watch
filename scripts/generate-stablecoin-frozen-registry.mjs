#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const SOURCE_JSON_REL = "shared/data/stablecoins/coins.generated.json";
const OUTPUT_TS_REL = "shared/data/stablecoins/coins.frozen.generated.ts";
const SOURCE_JSON_ABS = resolve(REPO_ROOT, SOURCE_JSON_REL);
const OUTPUT_TS_ABS = resolve(REPO_ROOT, OUTPUT_TS_REL);
const CHECK_MODE = process.argv.includes("--check");

/**
 * Synchronous FNV-1a 32-bit hash. Cheap, deterministic, and runs anywhere
 * (Node, Cloudflare Workers, browsers) without crypto APIs. Used purely as
 * a drift fingerprint between the frozen TS module and the source JSON;
 * collisions are not a security concern here.
 */
function fnv1a32(input) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = (hash + ((hash << 1) + (hash << 4) + (hash << 7) + (hash << 8) + (hash << 24))) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

function computeFingerprint(parsed) {
  // Stable input: re-stringify the parsed JSON so generator and runtime
  // hash the same canonical form regardless of source-file whitespace.
  return fnv1a32(JSON.stringify(parsed));
}

const rawJson = readFileSync(SOURCE_JSON_ABS, "utf8");
const parsed = JSON.parse(rawJson);

if (!Array.isArray(parsed)) {
  console.error(`[frozen-registry] ${SOURCE_JSON_REL} is not a JSON array`);
  process.exit(1);
}

const fingerprint = computeFingerprint(parsed);

const tsContents = `// @generated by scripts/generate-stablecoin-frozen-registry.mjs
// Do not edit by hand. Run \`node scripts/generate-stablecoin-frozen-registry.mjs\`
// after modifying any shared/data/stablecoins/coins/*.json file or
// shared/data/stablecoins/coins.generated.json.
//
// This module mirrors coins.generated.json as a typed snapshot so the
// Worker / Next.js runtime can skip the per-boot Zod parse. The embedded
// fingerprint lets registry.ts detect drift (e.g. someone edited a coin
// JSON without regenerating) and fall back to the live Zod path.

import type { StablecoinMeta } from "../../types";
import coinsGenerated from "./coins.generated.json";

/** FNV-1a 32-bit fingerprint of \`coins.generated.json\` at generation time. */
export const STABLECOIN_META_ASSETS_FROZEN_HASH = ${JSON.stringify(fingerprint)};

/**
 * Pre-validated stablecoin metas, exposed in source order. The generator
 * runs alongside \`npm run check:stablecoin-data\`, which performs the
 * authoritative Zod + invariant validation; consumers may use this array
 * directly when the runtime fingerprint matches
 * \`STABLECOIN_META_ASSETS_FROZEN_HASH\`.
 */
export const STABLECOIN_META_ASSETS_FROZEN: readonly StablecoinMeta[] =
  coinsGenerated as readonly StablecoinMeta[];
`;

if (CHECK_MODE) {
  const current = existsSync(OUTPUT_TS_ABS) ? readFileSync(OUTPUT_TS_ABS, "utf8") : "";
  if (current !== tsContents) {
    console.error(`${OUTPUT_TS_REL} is stale. Run: node scripts/generate-stablecoin-frozen-registry.mjs`);
    process.exit(1);
  }
  console.log(`${OUTPUT_TS_REL}: frozen registry snapshot is current (fingerprint ${fingerprint}, ${parsed.length} entries)`);
} else {
  mkdirSync(dirname(OUTPUT_TS_ABS), { recursive: true });
  writeFileSync(OUTPUT_TS_ABS, tsContents, "utf8");
  console.log(`${OUTPUT_TS_REL}: wrote frozen registry snapshot (fingerprint ${fingerprint}, ${parsed.length} entries)`);
}
