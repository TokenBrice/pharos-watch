const PINNED_ENQUEUE_HEAD =
  "INSERT INTO telegram_pending_alerts ( chat_id, message_html, disable_notification, created_at, not_before_at, "
  + "last_error_class, retry_after_sec, updated_at, dedupe_key, chunk_index, priority, source_type, alert_type, "
  + "expires_at, source_event_id, alert_scope_json, preference_generation, markup_policy_json ) VALUES (?, ?, ?, ?, "
  + "?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

const PINNED_HANDOFF_HEAD =
  "INSERT INTO telegram_pending_alerts ( chat_id, message_html, disable_notification, created_at, not_before_at, "
  + "last_error_class, retry_after_sec, updated_at, dedupe_key, chunk_index, priority, source_type, alert_type, "
  + "expires_at, source_event_id, alert_scope_json, preference_generation, markup_policy_json ) SELECT "
  + "target.chat_id, target.message_html, target.disable_notification, ?, NULL, NULL, NULL, ?, "
  + "target.pending_dedupe_key, target.chunk_index, CASE target.alert_type WHEN 'dews' THEN 20 WHEN 'depeg' THEN 10 "
  + "WHEN 'safety' THEN 20 WHEN 'launch' THEN 30 WHEN 'reserve' THEN 30 WHEN 'freeze' THEN 10 ELSE 30 END, "
  + "'risk_alert', target.alert_type, target.target_expires_at, target.source_event_id, target.alert_scope_json, "
  + "target.preference_generation, target.markup_policy_json FROM telegram_alert_job_targets target WHERE "
  + "target.source_event_id = ? AND target.plan_generation = ? AND target.status = 'planned' AND target.target_key "
  + "IN (SELECT value FROM json_each(?))";

const MESSAGE: BatchMessage = {
  chatId: "111",
  html: "<b>pin</b>",
  alertType: "depeg",
  chunkIndex: 0,
  disableNotification: false,
} as BatchMessage;

function captureEnqueueSql(): string {
  const captured: CapturedStatement[] = [];
  buildPendingAlertEnqueueStatement(capturingDb(captured), MESSAGE, 1_700_000_000);
  expect(captured).toHaveLength(1);
  return normalize(captured[0].sql);
}

function captureHandoffSql(): string {
  const captured: CapturedStatement[] = [];
  buildSetBasedPendingHandoffStatements(capturingDb(captured), "src-1", 3, 1_700_000_000, ["target-a"]);
  return normalize(captured[0].sql);
}

describe("telegram_pending_alerts upsert SQL", () => {
  it("pins the bind-parameterized enqueue form", () => {
    const sql = captureEnqueueSql();
    expect(sql.slice(0, sql.indexOf(CONFLICT_MARKER)).trim()).toBe(PINNED_ENQUEUE_HEAD);
    expect(sql.slice(sql.indexOf(CONFLICT_MARKER))).toBe(PINNED_CONFLICT_CLAUSE);
  });

  it("pins the set-based authoritative handoff form", () => {
    const sql = captureHandoffSql();
    expect(sql.slice(0, sql.indexOf(CONFLICT_MARKER)).trim()).toBe(PINNED_HANDOFF_HEAD);
    expect(sql.slice(sql.indexOf(CONFLICT_MARKER))).toBe(PINNED_CONFLICT_CLAUSE);
  });

  it("emits one conflict clause for both value sources", () => {
    const enqueue = captureEnqueueSql();
    const handoff = captureHandoffSql();
    expect(enqueue.slice(enqueue.indexOf(CONFLICT_MARKER)))
      .toBe(handoff.slice(handoff.indexOf(CONFLICT_MARKER)));
  });

  it("binds only the insert values now that the TTL constant is inlined", () => {
    const captured: CapturedStatement[] = [];
    buildPendingAlertEnqueueStatement(capturingDb(captured), MESSAGE, 1_700_000_000);
    expect(captured[0].binds).toHaveLength(18);
  });

  it("generates a priority arm for every canonical alert type", () => {
    const sql = normalize(pendingPrioritySql("target.alert_type"));
    expect(sql).toBe(
      "CASE target.alert_type WHEN 'dews' THEN 20 WHEN 'depeg' THEN 10 WHEN 'safety' THEN 20"
      + " WHEN 'launch' THEN 30 WHEN 'reserve' THEN 30 WHEN 'freeze' THEN 10 ELSE 30 END",
    );
  });

  it("keeps the conflict clause independent of the value source", () => {
    const values = normalize(buildPendingAlertUpsertSql("VALUES (1)"));
    const select = normalize(buildPendingAlertUpsertSql("SELECT 1"));
    expect(values.slice(values.indexOf(CONFLICT_MARKER)))
      .toBe(select.slice(select.indexOf(CONFLICT_MARKER)));
  });
});
