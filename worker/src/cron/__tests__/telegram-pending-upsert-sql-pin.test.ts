  + "excluded.created_at - 7200 THEN NULL ELSE telegram_pending_alerts.processing_owner END, processing_started_at "
  + "= CASE WHEN COALESCE( telegram_pending_alerts.expires_at, telegram_pending_alerts.created_at + 7200 ) <= "
  + "excluded.created_at OR telegram_pending_alerts.created_at < excluded.created_at - 7200 THEN NULL ELSE "
  + "telegram_pending_alerts.processing_started_at END, processing_expires_at = CASE WHEN COALESCE( "
  + "telegram_pending_alerts.expires_at, telegram_pending_alerts.created_at + 7200 ) <= excluded.created_at OR "
