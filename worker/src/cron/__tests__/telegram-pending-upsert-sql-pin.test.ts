/**
 * Byte-level pin for the `telegram_pending_alerts` upsert.
 *
 * Two producers write this row: the bind-parameterized `VALUES` form
 * (`lib/telegram-pending-queue.ts`) and the set-based `SELECT ... FROM
 * telegram_alert_job_targets` form (`telegram-alert-target-plans/delivery.ts`).
 * Both are generated by `buildPendingAlertUpsertSql`, so the conflict clause,
 * the TTL refresh predicate and the claim guard must be identical text; only
 * the value source differs. The pinned strings below were captured from the
 * pre-consolidation authoritative-handoff statement.
 */

interface CapturedStatement {
  sql: string;
  binds: unknown[];
}

function capturingDb(captured: CapturedStatement[]): D1Database {
  return makeNoopD1({
    prepare(sql: string) {
      const record: CapturedStatement = { sql, binds: [] };
      captured.push(record);
      const statement = {
        bind(...binds: unknown[]) {
          record.binds = binds;
          return statement;
        },
      };
      return statement as unknown as D1PreparedStatement;
    },
  });
}

function normalize(sql: string): string {
  return sql.replace(/\s+/g, " ").trim();
}

const CONFLICT_MARKER = "ON CONFLICT(dedupe_key) DO UPDATE SET";

