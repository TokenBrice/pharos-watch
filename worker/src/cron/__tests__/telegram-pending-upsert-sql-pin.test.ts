  + "telegram_pending_alerts.created_at + 7200 ) <= excluded.created_at OR telegram_pending_alerts.created_at < "
  + "excluded.created_at - 7200 THEN excluded.created_at ELSE telegram_pending_alerts.created_at END, attempts = "
  + "CASE WHEN COALESCE( telegram_pending_alerts.expires_at, telegram_pending_alerts.created_at + 7200 ) <= "
  + "excluded.created_at OR telegram_pending_alerts.created_at < excluded.created_at - 7200 THEN 0 ELSE "
  + "telegram_pending_alerts.attempts END, not_before_at = CASE WHEN COALESCE( telegram_pending_alerts.expires_at, "
  + "telegram_pending_alerts.created_at + 7200 ) <= excluded.created_at OR telegram_pending_alerts.created_at < "
  + "excluded.created_at - 7200 THEN excluded.not_before_at WHEN excluded.not_before_at IS NULL THEN "
  + "telegram_pending_alerts.not_before_at WHEN telegram_pending_alerts.not_before_at IS NULL THEN "
  + "excluded.not_before_at ELSE MAX(telegram_pending_alerts.not_before_at, excluded.not_before_at) END, "
  + "last_error_class = COALESCE(excluded.last_error_class, telegram_pending_alerts.last_error_class), "
  + "retry_after_sec = COALESCE(excluded.retry_after_sec, telegram_pending_alerts.retry_after_sec), updated_at = "
  + "excluded.updated_at, chunk_index = excluded.chunk_index, priority = "
  + "MIN(COALESCE(telegram_pending_alerts.priority, excluded.priority), excluded.priority), source_type = CASE WHEN "
  + "excluded.priority < COALESCE(telegram_pending_alerts.priority, excluded.priority) THEN excluded.source_type "
  + "ELSE telegram_pending_alerts.source_type END, alert_type = COALESCE(excluded.alert_type, "
  + "telegram_pending_alerts.alert_type), expires_at = CASE WHEN COALESCE( telegram_pending_alerts.expires_at, "
  + "telegram_pending_alerts.created_at + 7200 ) <= excluded.created_at OR telegram_pending_alerts.created_at < "
  + "excluded.created_at - 7200 THEN excluded.expires_at ELSE COALESCE(telegram_pending_alerts.expires_at, "
  + "excluded.expires_at) END, processing_owner = CASE WHEN COALESCE( telegram_pending_alerts.expires_at, "
