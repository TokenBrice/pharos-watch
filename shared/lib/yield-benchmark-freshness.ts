export function hasYieldBenchmarkUnitMismatch(row: {
  warningSignals: readonly string[];
  provenance?: { sourceKey?: string | null } | null;
}): boolean {
  const key = row.provenance?.sourceKey;
  return row.warningSignals.includes("benchmark-unit-mismatch")
    || key === "onchain:xgld-unitas" || key === "linked-variant:xgld-unitas:onchain:xgld-unitas";
}

/** Convert the named CMT investment-basis quote to effective annual percent. */
export function getYieldBenchmarkComparisonApy(meta: {
  key?: YieldBenchmarkKey;
  source?: string | null;
  rate: number;
}): number {
  return meta.key === "USD" && (meta.source === "fred-dgs3mo" || meta.source === "treasury-yield-xml")
    ? meta.rate + meta.rate ** 2 / 400
    : meta.rate;
}

// Benchmark timestamps are generated by external publishers and may lead the
// worker clock slightly; larger leads are unusable rather than "age zero".
const YIELD_BENCHMARK_MAX_FUTURE_SKEW_SEC = 5 * 60;

const CETES_PLACEMENT_WEEKDAY = 4;
const CETES_PLACEMENT_GRACE_SEC = 36 * HOUR_SECONDS;
const CETES_MAX_RECORD_AGE_SEC = WEEK_SECONDS + 2 * DAY_SECONDS + CETES_PLACEMENT_GRACE_SEC;
const MEXICO_FIXED_BANK_HOLIDAYS = new Set(["01-01", "05-01", "09-16", "11-02", "12-12", "12-25"]);

/**
 * Per-key bound on the age of a benchmark's own observation (`recordDate`).
 * A fetch that just succeeded says nothing about the data it carried: a frozen
 * or rewound upstream keeps returning an old CSV, and the fetch-age TTL alone
 * would stamp it as current market data forever. Bounds follow each series'
 * real publication calendar, not one size: daily/overnight series get five
 * days (a long weekend plus one failed run), keys whose calendars have
 * multi-day holiday clusters carry more (see per-key comments), and CAD is
 * the Bank of Canada's monthly announced Bank rate.
 */
export const YIELD_BENCHMARK_RECORD_MAX_AGE_SEC: Record<YieldBenchmarkKey, number> = Object.fromEntries(
  YIELD_BENCHMARK_KEY_VALUES.map((key) => [
    key, key === "MXN" ? CETES_MAX_RECORD_AGE_SEC : YIELD_BENCHMARK_DEFINITIONS[key].recordMaxAgeDays * DAY_SECONDS,
  ]),
) as Record<YieldBenchmarkKey, number>;

function isMexicoPlacementHoliday(daySec: number): boolean {
  const day = new Date(daySec * 1_000);
  const easter = easterSundayUtcDaySec(day.getUTCFullYear());
  return daySec === easter - 3 * DAY_SECONDS || daySec === easter - 2 * DAY_SECONDS
    || MEXICO_FIXED_BANK_HOLIDAYS.has(day.toISOString().slice(5, 10));
}

/**
 * Banxico dates SF43936 by weekly placement: Thursday, or the nearest banking
 * day (prefer the earlier one) if Thursday is closed. The grace allows the daily
 * benchmark fetch to see the next effective placement.
 * https://www.banxico.org.mx/elib/mercado-valores-gub/oebps/Text/ii.html
 * https://sidof.segob.gob.mx/notas/5775684
 */
export function getYieldBenchmarkRecordMaxAgeSeconds(
  key: YieldBenchmarkKey,
  recordDate: string | null | undefined,
  publishedBound?: number | null,
): number {
  const maxAge = YIELD_BENCHMARK_RECORD_MAX_AGE_SEC[key];
  if (key !== "MXN") return publishedBound ?? maxAge;
  const recordAt = benchmarkRecordObservedAtSeconds(recordDate);
  if (recordAt == null) return maxAge;
  const weekday = new Date(recordAt * 1_000).getUTCDay() || 7;
  const thursday = recordAt + WEEK_SECONDS + (CETES_PLACEMENT_WEEKDAY - weekday) * DAY_SECONDS;
  const wednesday = thursday - DAY_SECONDS;
  const friday = thursday + DAY_SECONDS;
  const placement = !isMexicoPlacementHoliday(thursday) ? thursday
    : !isMexicoPlacementHoliday(wednesday) ? wednesday
      : !isMexicoPlacementHoliday(friday) ? friday : thursday;
  return Math.min(maxAge, placement - recordAt + CETES_PLACEMENT_GRACE_SEC);
}

export function isYieldBenchmarkFixingEffective(
  key: YieldBenchmarkKey,
  recordDate: string | null | undefined,
  nowSec: number,
): boolean {
  if (!isValidIsoDateOnly(recordDate) || !Number.isFinite(nowSec)) return false;
  if (key === "MXN") {
    const effectiveDate = localDateInIanaTimezone(nowSec * 1_000, "America/Mexico_City");
    return effectiveDate != null && recordDate <= effectiveDate;
  }
  return Date.parse(`${recordDate}T00:00:00Z`) / 1_000 <= nowSec;
}

/**
 * Per-key bound on a newly fetched market rate's relative move against the last
 * published market observation. The provider range guard only rejects values
 * outside a broad band (-10..20, 100 for TRY/RUB), so a publisher that changes
 * units or column meaning while staying in range (4.3 -> 0.43) would otherwise
 * publish as a current benchmark. High-rate keys (policy rates that can move by
 * whole points) get a wider band; the unit-scale window below still catches a
 * silent 10x/0.1x rescale for every key.
 */
const YIELD_BENCHMARK_MAX_RELATIVE_CHANGE: Record<YieldBenchmarkKey, number> = Object.fromEntries(
  YIELD_BENCHMARK_KEY_VALUES.map((key) => [key, YIELD_BENCHMARK_DEFINITIONS[key].maxRelativeChange]),
) as Record<YieldBenchmarkKey, number>;

/**
 * Ratios only a unit change produces, whatever the key's own band. The bounds
 * are unconditional so a wide policy-rate band cannot admit a 100x
 * percent->fraction drift.
 */
const UNIT_SCALE_RATIO_MAX = 0.2;
const UNIT_SCALE_RATIO_INVERSE_MIN = 5;
/**
 * Absolute move (percentage points) at or below which no relative band applies:
 * 50 bp covers ordinary central-bank steps at low or zero levels, including a
 * sign crossing. Only larger moves are graded against the key's relative band.
 */
const RATE_ABSOLUTE_MOVE_ALWAYS_PLAUSIBLE = 0.5;
/** A later fixing within this relative tolerance can confirm a rejected level. */
const RATE_CONFIRMATION_RELATIVE_TOLERANCE = 0.05;

export type YieldBenchmarkRateRejection = "non-finite" | "unit-scale" | "relative-band";

interface BenchmarkRateConfirmationEvidence {
  recordDate: string;
  nowSec: number;
  previousRejection: { rate: number; recordDate: string | null; fetchedAt: number | null };
}

export interface YieldBenchmarkRateAssessment {
  accepted: boolean;
  rejection: YieldBenchmarkRateRejection | null;
  /** The rejected level repeated on the next observation and was accepted as a shift. */
  confirmedLevelShift: boolean;
}

function sameRejectedLevel(rate: number, previousRejectedRate: number): boolean {
  const scale = Math.max(Math.abs(rate), Math.abs(previousRejectedRate));
  return Math.abs(rate - previousRejectedRate) <= scale * RATE_CONFIRMATION_RELATIVE_TOLERANCE;
}

function isUnitScaleRatio(ratio: number): boolean {
  return ratio <= UNIT_SCALE_RATIO_MAX || ratio >= UNIT_SCALE_RATIO_INVERSE_MIN;
}

/**
 * Grade a freshly parsed market rate against the last published market
 * observation. A relative-band rejection may be confirmed only by a later
 * effective fixing at the same out-of-band level within tolerance; a unit-scale
 * ratio is never confirmation-eligible, so a persistent 100x drift stays rejected.
 */
export function assessYieldBenchmarkRate(
  key: YieldBenchmarkKey,
  rate: number,
  previousMarketRate: number | null | undefined,
  evidence?: BenchmarkRateConfirmationEvidence,
): YieldBenchmarkRateAssessment {
  // Policy benchmarks may legitimately publish zero or negative observations.
  if (!Number.isFinite(rate)) {
    return { accepted: false, rejection: "non-finite", confirmedLevelShift: false };
  }
  if (previousMarketRate == null || !Number.isFinite(previousMarketRate) || previousMarketRate === 0) {
    return { accepted: true, rejection: null, confirmedLevelShift: false };
  }
  if (Math.abs(rate - previousMarketRate) <= RATE_ABSOLUTE_MOVE_ALWAYS_PLAUSIBLE) {
    return { accepted: true, rejection: null, confirmedLevelShift: false };
  }
  const ratio = rate / previousMarketRate;
  if (isUnitScaleRatio(ratio)) {
    return { accepted: false, rejection: "unit-scale", confirmedLevelShift: false };
  }
  if (Math.abs(ratio - 1) <= YIELD_BENCHMARK_MAX_RELATIVE_CHANGE[key]) {
    return { accepted: true, rejection: null, confirmedLevelShift: false };
  }
  const rejected = evidence?.previousRejection;
  if (evidence && rejected?.recordDate
    && evidence.recordDate > rejected.recordDate
    && rejected.fetchedAt != null && rejected.fetchedAt <= evidence.nowSec
    && isYieldBenchmarkFixingEffective(key, rejected.recordDate, rejected.fetchedAt)
    && isYieldBenchmarkFixingEffective(key, evidence.recordDate, evidence.nowSec)
    && Number.isFinite(rejected.rate)
    && !isUnitScaleRatio(rejected.rate / previousMarketRate)
    && sameRejectedLevel(rate, rejected.rate)) {
    return { accepted: true, rejection: null, confirmedLevelShift: true };
  }
  return { accepted: false, rejection: "relative-band", confirmedLevelShift: false };
}

/**
 * Whether a freshly parsed market rate may replace the published benchmark
 * without a confirmation. A rejected rate keeps the previous retained value and
 * names `<key>-rate-out-of-band` in run metadata.
 */
export function isYieldBenchmarkRatePlausible(
  key: YieldBenchmarkKey,
  rate: number,
  previousMarketRate: number | null | undefined,
): boolean {
  return assessYieldBenchmarkRate(key, rate, previousMarketRate).accepted;
}

/**
 * Age of a benchmark's own observation at `nowSec`. `null` when the entry
 * carries no parseable observation date. Small clock skew is tolerated, but a
 * farther-future observation returns a negative age so callers fail closed.
 */
export function benchmarkRecordAgeSeconds(
  recordDate: string | null | undefined,
  nowSec: number,
): number | null {
  const observedAt = benchmarkRecordObservedAtSeconds(recordDate);
  if (observedAt == null) return null;
  const ageSec = nowSec - observedAt;
  return ageSec < 0 && ageSec >= -YIELD_BENCHMARK_MAX_FUTURE_SKEW_SEC ? 0 : ageSec;
}

/** A date-only fixing has daily precision. Use UTC midnight as its date bucket. */
export function benchmarkRecordObservedAtSeconds(recordDate: string | null | undefined): number | null {
  return isValidIsoDateOnly(recordDate) ? Date.parse(`${recordDate}T00:00:00Z`) / 1_000 : null;
}

/**
 * Classify a registry entry from its own evidence: the hard 48h fetch-age TTL,
 * plus — when the caller supplies the key's observation bound — the age of the
 * observation the fetch carried. Both are `max`-combined. Missing, unparseable,
 * or farther-future bounded observations are stale. Shared so the API read path
 * and the cron write path apply one rule without crossing the worker api/cron
 * import boundary.
 */
export function classifyYieldBenchmarkFreshness(meta: {
  key?: YieldBenchmarkKey;
  ageSeconds: number | null;
  isFallback: boolean;
  fallbackMode: string | null;
}, options?: {
  selectionMode?: YieldBenchmarkSelectionMode | null;
  /** The benchmark's own observation date, as published on the registry entry. */
  recordDate?: string | null;
  /** Per-key bound, normally `YIELD_BENCHMARK_RECORD_MAX_AGE_SEC[key]`. */
  maxRecordAgeSec?: number | null;
  /** Assessment clock; defaults to the current time. */
  nowSec?: number;
}): YieldBenchmarkFreshness {
  if (
    meta.ageSeconds == null ||
    !Number.isFinite(meta.ageSeconds) ||
    meta.ageSeconds < 0 ||
    meta.ageSeconds > YIELD_BENCHMARK_SCORE_TTL_SEC
  ) {
    return "stale";
  }
  const nowSec = options?.nowSec ?? Math.floor(Date.now() / 1000);
  const recordDate = options?.recordDate;
  const maxRecordAgeSec = meta.key === "MXN"
    ? getYieldBenchmarkRecordMaxAgeSeconds(meta.key, recordDate)
    : options?.maxRecordAgeSec;
  if (maxRecordAgeSec != null && Number.isFinite(maxRecordAgeSec)) {
    if (meta.key === "MXN" && !isYieldBenchmarkFixingEffective(meta.key, recordDate, nowSec)) return "stale";
    const recordAgeSec = benchmarkRecordAgeSeconds(recordDate, nowSec);
    if (recordAgeSec == null || recordAgeSec < 0 || recordAgeSec > maxRecordAgeSec) {
      return "stale";
    }
  }
  if (
    meta.isFallback ||
    meta.fallbackMode != null ||
    options?.selectionMode === "fallback-usd"
  ) {
    return "degraded";
  }
  return "healthy";
}
