export const dynamic = "force-static";

/**
 * Git-derived last-edited dates for static pages (avoid misleading Google with build-time dates).
 * Auto-generated by `scripts/maintenance/generate-sitemap-dates.ts` during prebuild.
 */
const LAST_EDITED: Record<string, string> = sitemapDates;
const fundingCosts = CostsFileSchema.parse(costsData);
const fundingDonations = DonationsFileSchema.parse(donationsData);
const typedSummaries = aiSummaries as StablecoinAiSummariesById;
const TOP_STABLECOINS_DATASET = PUBLIC_DATASET_CURRENT_EXPORTS["top-stablecoins"] as {
  _meta: { asOfISO: string };
};

type SitemapChangeFrequency = NonNullable<MetadataRoute.Sitemap[number]["changeFrequency"]>;
type StaticPageSpec = readonly [
  path: string,
  changeFrequency: SitemapChangeFrequency,
  priority: number,
  resolveLastModified?: (path: string) => Date,
];
export const METHODOLOGY_CHANGELOG_SITEMAP_PATHS = SHARED_METHODOLOGY_CHANGELOG_SITEMAP_PATHS;


/** Resolve a Git-derived edit date without turning an unmapped route into a deploy-time change. */
function lastEdited(path: string, fallbackPath = "/"): Date {
  const iso = LAST_EDITED[path] ?? LAST_EDITED[fallbackPath];
  if (!iso) {
    throw new Error(
      `Missing sitemap last-modified date for ${path} (fallback: ${fallbackPath}). ` +
        "Regenerate src/generated/sitemap-dates.json.",
    );
  }
  return new Date(iso);
}

function fundingLastModified(): Date {
  return new Date(
    Math.max(
      lastEdited("/funding/").getTime(),
      fundingCosts.last_reviewed_at * 1000,
      fundingDonations.last_updated_at * 1000,
    ),
  );
}

/** The homepage bakes the current top-stablecoins dataset, not the depeg/digest clock. */
function homeLastModified(): Date {
  const asOfMs = Date.parse(TOP_STABLECOINS_DATASET._meta.asOfISO);
  return new Date(Math.max(lastEdited("/").getTime(), Number.isFinite(asOfMs) ? asOfMs : 0));
}

/** /safety-scores/ bakes the dated scores-latest preview, not only its route shell. */
function safetyScoresLastModified(): Date {
  const publishedAtMs = (getSafetyScoresPreview()?.publishedAtSec ?? 0) * 1000;
  return new Date(Math.max(lastEdited("/safety-scores/").getTime(), Number.isFinite(publishedAtMs) ? publishedAtMs : 0));
}

/** The digest hub lists the digest set; its own newest publication dates it. */
function digestIndexLastModified(): Date {
  return new Date(
    Math.max(
      lastEdited("/digest/").getTime(),
      ...DIGEST_ENTRIES.map((digest) => digest.generatedAt * 1000),
    ),
  );
}

/** The depeg hub lists events; the newest event date is its content clock. */
function depegIndexLastModified(): Date {
  return new Date(
    Math.max(
      lastEdited("/depeg/").getTime(),
      ...DEPEG_EVENT_ENTRIES.map((event) => (event.endedAt ?? event.startedAt) * 1000),
    ),
  );
}

/** A summary edit belongs to this profile, not every row in its shared JSON file. */
function stablecoinLastModified(id: string): Date {
  const edited = lastEdited(buildStablecoinUrl(id));
  const summaryMs = Date.parse(typedSummaries[id]?.updatedAt ?? "");
  return Number.isFinite(summaryMs) && summaryMs > edited.getTime() ? new Date(summaryMs) : edited;
}

/** /changelog/ moves when a new weekly entry lands, not with the daily data snapshot. */
function changelogLastModified(): Date {
  return new Date(
    Math.max(
      lastEdited("/changelog/").getTime(),
      ...changelogs.map((entry) => new Date(entry.dateRange.to).getTime()),
    ),
  );
}

/** /docs/ moves when a published doc is edited, not with the daily data snapshot. */
function docsIndexLastModified(): Date {
  const metadata = docsMetadata as Record<string, { dateModified: string }>;
  return new Date(
    Math.max(
      lastEdited("/docs/").getTime(),
      ...PUBLIC_DOCS.map((doc) => {
        const meta = metadata[doc.slug];
        return meta ? new Date(meta.dateModified).getTime() : 0;
      }),
    ),
  );
}

function comparisonLastModified(page: (typeof STATIC_COMPARISON_PAGES)[number]): Date {
  return new Date(
    Math.max(
      lastEdited(buildStablecoinUrl(page.left.id)).getTime(),
      lastEdited(buildStablecoinUrl(page.right.id)).getTime(),
      page.editorial ? new Date(page.editorial.updatedAt).getTime() : 0,
    ),
  );
}

function buildStaticSitemapEntries(
  specs: readonly StaticPageSpec[],
  defaultLastModified: (path: string) => Date,
): MetadataRoute.Sitemap {
  return specs.map(([path, changeFrequency, priority, resolveLastModified = defaultLastModified]) => ({
    url: `${SITE_URL}${path}`,
    lastModified: resolveLastModified(path),
    changeFrequency,
    priority,
  }));
}

export default function sitemap(): MetadataRoute.Sitemap {
  const staticDateResolvers: Record<string, (path: string) => Date> = {
    "/": homeLastModified,
    "/depeg/": depegIndexLastModified,
    "/digest/": digestIndexLastModified,
    "/safety-scores/": safetyScoresLastModified,
    "/funding/": fundingLastModified,
    "/changelog/": changelogLastModified,
    "/depeg/archive/": (path) => lastEdited(path, "/depeg/"),
    "/api/reference/": (path) => lastEdited(path, API_ACCESS_PAGE_PATH),
    "/docs/": docsIndexLastModified,
  };
  const withDateResolver = ([path, changeFrequency, priority]: readonly [string, SitemapChangeFrequency, number]): StaticPageSpec =>
    [path, changeFrequency, priority, staticDateResolvers[path]];
  const staticPageSpecs = PUBLIC_PRIMARY_ROUTES.map(withDateResolver);
  const referencePageSpecs = PUBLIC_REFERENCE_ROUTES
    .filter(([path]) => path !== "/docs/")
    .map(withDateResolver);

  const staticPages: MetadataRoute.Sitemap = [
    ...buildStaticSitemapEntries(staticPageSpecs, lastEdited),
    ...METHODOLOGY_CHANGELOG_SITEMAP_PATHS.map((path) => ({
      url: `${SITE_URL}${path}`,
      lastModified: lastEdited(path),
      changeFrequency: "monthly" as const,
      priority: 0.4,
    })),
    ...METHODOLOGY_HISTORY_ARCHIVES.map((archive) => ({
      url: `${SITE_URL}${archive.path}`,
      lastModified: lastEdited(archive.path, archive.changelog.publicPath),
      changeFrequency: "monthly" as const,
      priority: 0.3,
    })),
    ...CHANGELOG_MONTH_ARCHIVES.map((archive) => ({
      url: `${SITE_URL}${archive.path}`,
      lastModified: lastEdited(archive.path, "/changelog/"),
      changeFrequency: "monthly" as const,
      priority: 0.3,
    })),
    ...buildStaticSitemapEntries(referencePageSpecs, lastEdited),
  ];

  const stablecoinPages: MetadataRoute.Sitemap = CLIENT_TRACKED_STABLECOINS.map((coin) => ({
    url: `${SITE_URL}${buildStablecoinUrl(coin.id)}`,
    lastModified: stablecoinLastModified(coin.id),
    changeFrequency: "daily" as const,
    priority: 0.6,
  }));

  const chainPages: MetadataRoute.Sitemap = [
    {
      url: `${SITE_URL}/chains/`,
      lastModified: lastEdited("/chains/"),
      changeFrequency: "daily",
      priority: 0.8,
    },
    // Chain pages move with their route's edit date, not the daily data
    // snapshot: the digest timestamp claimed 128 simultaneous changes a day.
    ...PUBLIC_ROUTE_FAMILY_PATHS.chains.map((path) => ({
      url: `${SITE_URL}${path}`,
      lastModified: lastEdited(path, "/chains/"),
      changeFrequency: "daily" as const,
      priority: 0.5,
    })),
  ];

  const pegPages: MetadataRoute.Sitemap = PUBLIC_ROUTE_FAMILY_PATHS.pegHubs.map((path) => ({
    url: `${SITE_URL}${path}`,
    lastModified: lastEdited(path, "/stablecoins/"),
    changeFrequency: "daily" as const,
    priority: 0.7,
  }));

  const digestPages: MetadataRoute.Sitemap = INDEXABLE_DIGEST_ENTRIES.map((d) => ({
    url: `${SITE_URL}/digest/${d.date}/`,
    lastModified: new Date(d.generatedAt * 1000),
    changeFrequency: "never" as const,
    priority: 0.5,
  }));

  const depegEventPages: MetadataRoute.Sitemap = INDEXABLE_DEPEG_EVENT_ENTRIES.map((e) => ({
    url: `${SITE_URL}/depeg/${e.slug}/`,
    lastModified: new Date(
      Math.max(
        e.endedAt ?? e.startedAt,
        COLLIDING_DEPEG_EVENT_SLUGS.has(e.slug) ? DEPEG_COLLISION_CONTENT_REVISED_AT_SECONDS : 0,
      ) * 1000,
    ),
    changeFrequency: (e.endedAt ? "never" : "daily") as "never" | "daily",
    priority: 0.55,
  }));

  const taxonomyPages: MetadataRoute.Sitemap = PUBLIC_ROUTE_FAMILY_PATHS.taxonomies.map((path) => ({
    url: `${SITE_URL}${path}`,
    lastModified: lastEdited(path, "/stablecoins/"),
    changeFrequency: "weekly" as const,
    priority: 0.7,
  }));

  const learnMechanismPages: MetadataRoute.Sitemap = [
    {
      url: `${SITE_URL}/learn/mechanisms/`,
      lastModified: lastEdited("/learn/mechanisms/"),
      changeFrequency: "monthly",
      priority: 0.6,
    },
    ...PUBLIC_ROUTE_FAMILY_PATHS.mechanisms.map((path) => ({
      url: `${SITE_URL}${path}`,
      lastModified: lastEdited(path, "/learn/mechanisms/"),
      changeFrequency: "monthly" as const,
      priority: 0.7,
    })),
  ];

  const learnCaseStudyPages: MetadataRoute.Sitemap = [
    {
      url: `${SITE_URL}/learn/case-studies/`,
      lastModified: lastEdited("/learn/case-studies/"),
      changeFrequency: "monthly",
      priority: 0.6,
    },
    ...CASE_STUDY_LIST.map((study) => ({
      url: `${SITE_URL}/learn/case-studies/${study.slug}/`,
      lastModified: lastEdited(`/learn/case-studies/${study.slug}/`),
      changeFrequency: "monthly" as const,
      priority: 0.7,
    })),
  ];

  // /blog/ hub lives in referencePageSpecs above; these are the post detail
  // pages. Per-post lastmod comes from the git-derived sitemap-dates entry
  // (see addBlogDates in generate-sitemap-dates.ts).
  const blogPages: MetadataRoute.Sitemap = PUBLIC_ROUTE_FAMILY_PATHS.blogPosts.map((path) => ({
    url: `${SITE_URL}${path}`,
    lastModified: lastEdited(path),
    changeFrequency: "monthly" as const,
    priority: 0.5,
  }));

  const comparisonPages: MetadataRoute.Sitemap = STATIC_COMPARISON_PAGES.map((page) => ({
    url: `${SITE_URL}${page.href}`,
    lastModified: comparisonLastModified(page),
    changeFrequency: "monthly" as const,
    priority: 0.6,
  }));

  const docsIndex = buildStaticSitemapEntries(
    PUBLIC_REFERENCE_ROUTES.filter(([path]) => path === "/docs/").map(withDateResolver),
    lastEdited,
  );

  const docsPages: MetadataRoute.Sitemap = PUBLIC_DOCS.map((doc) => {
    const meta = (docsMetadata as Record<string, { dateModified: string }>)[doc.slug];
    return {
      url: `${SITE_URL}/docs/${doc.slug}/`,
      lastModified: meta ? new Date(meta.dateModified) : lastEdited("/docs/"),
      changeFrequency: "monthly" as const,
      priority: 0.5,
    };
  });

  // RSS feeds (/feed/<topic>.xml) and public datasets (.csv/.json) are excluded
  // from the sitemap — both are non-HTML URLs and the SEO check rejects entries
  // without HTML artifacts. They remain discoverable via <link rel="alternate">
  // tags, the footer "Subscribe" cluster, /llms.txt, and /api/.

  return [
    ...staticPages,
    ...stablecoinPages,
    ...chainPages,
    ...pegPages,
    ...taxonomyPages,
    ...learnMechanismPages,
    ...learnCaseStudyPages,
    ...blogPages,
    ...comparisonPages,
    ...digestPages,
    ...depegEventPages,
    ...docsIndex,
    ...docsPages,
  ];
}
